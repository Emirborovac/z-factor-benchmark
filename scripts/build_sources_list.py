"""Write data/processed/SOURCES.md: the 40 studies the benchmark is made of.

The measurements in this benchmark are other people's work. The manuscript cites
them individually, but the manuscript is not in this repository, so the
repository needs its own attribution list. Generated from the benchmark itself
so it cannot drift from the data.

Run:  python -X utf8 scripts/build_sources_list.py
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
TB = ROOT / "data" / "processed" / "test_b.parquet"
OUT = ROOT / "data" / "processed" / "SOURCES.md"

HEADER = """# Sources of the benchmark

Every measurement in `test_b.parquet` comes from one of the studies below,
distributed as machine-readable records in the NIST ThermoML archive
([doi:10.18434/mds2-2422](https://doi.org/10.18434/mds2-2422)).

**If you use this benchmark, cite these studies.** They are the experimental
work; this repository only compiles it. Citing the compilation is not a
substitute.

`n` is the number of gas-phase points contributed to the full benchmark, and
`n(NG)` the number falling inside the natural-gas domain used for the primary
comparison ($x_{CH_4} \\ge 0.5$, $T_{pr} \\le 3.0$, $T \\le 500$ K).

Generated by `scripts/build_sources_list.py`.

"""


def main() -> None:
    t = pd.read_parquet(TB)
    ng = ((t.x_methane >= 0.5) & (t.T_K <= 500)).to_numpy()

    rows = []
    for doi, g in t.groupby("doi"):
        m = ng[g.index.to_numpy()]
        rows.append((str(doi), len(g), int(m.sum()),
                     float(g.T_K.min()), float(g.T_K.max()),
                     float(g.P_MPa.min()), float(g.P_MPa.max())))
    rows.sort(key=lambda r: -r[1])

    L = [HEADER,
         "| # | DOI | n | n(NG) | T (K) | p (MPa) |",
         "|---:|---|---:|---:|---|---|"]
    for i, (doi, n, nng, t0, t1, p0, p1) in enumerate(rows, 1):
        L.append(f"| {i} | [{doi}](https://doi.org/{doi}) | {n} | {nng} | "
                 f"{t0:.0f}–{t1:.0f} | {p0:.3f}–{p1:.1f} |")
    L.append("")
    L.append(f"**{len(rows)} studies, {len(t):,} points** "
             f"({int(ng.sum()):,} in the natural-gas domain).")
    L.append("")
    L.append("One further source was excluded by the pre-declared screen "
             "described in `DATASHEET.md`; it is named there.")
    L.append("")

    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} studies, {len(t):,} points")


if __name__ == "__main__":
    main()
