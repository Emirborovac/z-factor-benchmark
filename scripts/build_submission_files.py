r"""Produce the plain-text files Elsevier's submission form asks for.

The submission form has separate upload slots for Abstract, Highlights and Cover
letter. All three are extracted from or written alongside the manuscript so they
cannot disagree with it.

Also bundles the LaTeX sources into one archive for the "LaTeX source files"
slot, so a compiled PDF is not needed: Elsevier's system builds the PDF from the
uploaded .tex.

Writes:
  paper/abstract.txt        plain text, no markup
  paper/highlights.txt      five lines (also written by build_highlights.py)
  paper/cover_letter.md     DRAFT for the author to review and edit
  paper/latex_sources.zip   refs.bib + all figure PDFs

Run:  python -X utf8 scripts/build_submission_files.py
"""
from __future__ import annotations

import re
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / "paper"
TEX = PAPER / "manuscript.tex"

BS = chr(92)


def detex_plain(s: str) -> str:
    """Manuscript LaTeX -> plain text, for a form field that accepts no markup."""
    s = s.replace(BS + "%", "%").replace(BS + "&", "&")
    s = re.sub(re.escape(BS) + r"mathrm\{([^{}]*)\}", r"\1", s)
    for a, b in [("le", "<="), ("ge", ">="), ("times", "x"), ("mu", "u"),
                 ("pm", "+/-"), ("approx", "~")]:
        s = s.replace(BS + a, b)
    s = re.sub(r"\$([^$]*)\$", r"\1", s)
    s = re.sub(r"\^\{?([0-9-]+)\}?", r"^\1", s)
    s = re.sub(r"_\{([^{}]*)\}", r"_\1", s)
    s = re.sub(re.escape(BS) + r"[a-zA-Z]+\*?", "", s)
    s = s.replace("{", "").replace("}", "")
    s = s.replace("---", " - ").replace("--", "-").replace("~", " ")
    return re.sub(r"\s+", " ", s).strip()


COVER = """# Cover letter

DRAFT - review, edit to your own voice, and delete this line before uploading.

Dear Editor,

I submit for your consideration the manuscript "A neural surrogate for the
natural-gas compressibility factor: reference-equation accuracy from synthetic
training data alone, benchmarked on 2426 independent laboratory measurements",
for publication as a research article.

The compressibility factor of natural gas is obtained either from inexpensive
empirical correlations or from reference equations of state that require the full
molar composition and an iterative density solve. Machine learning has been
proposed as a bridge between the two for fifteen years, and the reported gains
are large. Almost all of those studies, however, are trained and tested on values
digitised from the 1942 Standing-Katz chart - the same chart to which the
correlations they outperform were originally fitted. Their reported improvements
have therefore never had to survive contact with independent laboratory
measurements, because no common test set of measured compressibility factors with
absolute inputs has been available.

This manuscript makes that test set available. I assembled 6726 experimental
gas-phase measurements from 40 published studies in the NIST ThermoML archive,
each carrying absolute pressure, temperature and full molar composition, so that
the compressibility factor follows exactly from the measured quantities with no
chart, correlation or equation of state involved. On the natural-gas domain of
this benchmark - 2426 points from 10 independent laboratories - I evaluate six
established methods and a residual neural surrogate trained exclusively on
synthetic states generated by a reference equation.

Three results seem to me worth the editor's attention. First, the surrogate
attains an average absolute deviation of 0.789%, statistically indistinguishable
from AGA8-DETAIL at 0.769% and ahead of GERG-2008 at 0.917%, while reducing the
error of the Dranchuk-Abou-Kassem, Hall-Yarborough and Dranchuk-Purvis-Robinson
correlations by 1.10 to 1.14 percentage points at every one of the ten
laboratories - and it achieves this without any laboratory measurement entering
training, so the benchmark is a genuine held-out test. Second, a controlled
experiment holding states, architecture, training recipe and random seed fixed,
and changing only the reference equation that generated the training labels,
moves test accuracy from 0.923% to 0.789%. The accuracy of such a surrogate is
therefore governed by the equation it is distilled from rather than by its
architecture, which has a direct consequence for how this literature should
report its methods. Third, a search over 31 functional families and 186
leave-one-laboratory-out fits shows that residual corrections fitted to
laboratory data transfer for the empirical correlations but for none of the
reference equations or the surrogate, indicating that the remaining error of the
latter is measurement scatter rather than anything learnable.

I have tried to be explicit about what this work does not show. The surrogate
does not beat AGA8-DETAIL; on this benchmark that equation remains the most
accurate method available and the manuscript makes no claim of superiority over
it. I also measured the computational cost that surrogate papers customarily
assert, and report that a fixed-depth network is not intrinsically cheap: it
costs 14.7 microseconds per state on one processor against 5.5 for the reference
equation, and becomes the fastest method only when batched on a graphics
processor. Negative results, the applicability-domain limits, and the ways in
which the model inherits its teacher's blind spots are reported in the same
detail as the improvements.

The benchmark, the trained model and all code required to reproduce every figure
and table are openly available at
https://github.com/Emirborovac/z-factor-benchmark. The 40 constituent
experimental studies are cited individually, since the measurements are their
authors' work.

This manuscript is original, has not been published elsewhere, and is not under
consideration by another journal. I am the sole author, I have no competing
interests to declare, and I am submitting as an independent researcher.

Thank you for your consideration.

Yours sincerely,

Emir Borovac
Independent Researcher
emirborovac@rippleit-co.com
"""


def main() -> None:
    tex = TEX.read_text(encoding="utf-8")
    tex_nocomment = re.sub(r"(?m)^\s*%%.*$", "", tex)

    # ---- abstract ---------------------------------------------------------
    ab = tex_nocomment.split(BS + "begin{abstract}", 1)[1] \
                      .split(BS + "end{abstract}", 1)[0]
    abstract = detex_plain(ab)
    (PAPER / "abstract.txt").write_text(abstract + "\n", encoding="utf-8")
    n_words = len(abstract.split())

    # ---- highlights -------------------------------------------------------
    hb = tex_nocomment.split(BS + "begin{highlights}", 1)[1] \
                      .split(BS + "end{highlights}", 1)[0]
    items = [detex_plain(i) for i in
             re.findall(re.escape(BS) + r"item\s+(.+)", hb)]
    (PAPER / "highlights.txt").write_text("\n".join(items) + "\n",
                                          encoding="utf-8")

    # ---- cover letter -----------------------------------------------------
    (PAPER / "cover_letter.md").write_text(COVER, encoding="utf-8")

    # ---- LaTeX source bundle ---------------------------------------------
    zp = PAPER / "latex_sources.zip"
    figs = sorted((PAPER / "figures").glob("*.pdf"))
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        z.write(PAPER / "refs.bib", "refs.bib")
        for f in figs:
            z.write(f, f"figures/{f.name}")
    print(f"abstract.txt        {n_words} words")
    print(f"highlights.txt      {len(items)} lines, "
          f"max {max(len(i) for i in items)} chars (cap 85)")
    print(f"cover_letter.md     {len(COVER.split())} words (DRAFT)")
    print(f"latex_sources.zip   refs.bib + {len(figs)} figure PDFs, "
          f"{zp.stat().st_size / 1024:.0f} kB")
    if n_words > 250:
        raise SystemExit(f"abstract is {n_words} words, over the 250 cap")
    if any(len(i) > 85 for i in items):
        raise SystemExit("a highlight exceeds 85 characters")


if __name__ == "__main__":
    main()
